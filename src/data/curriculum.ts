const slug = (s: string) => Array.from(s).map((c) => c.codePointAt(0)!.toString(36)).join('')

export const units: Unit[] = seeds.map((seed, i) => {
  const id = `u${i + 1}`
  return {
    id,
    index: i,
    title: seed.title,
    subtitle: seed.subtitle,
    hanzi: seed.hanzi,
    color: seed.color,
    shadow: seed.shadow,
    tip: seed.tip,
    words: seed.words.map(([hanzi, pinyin, ru, emoji, note]) => ({
      id: `w-${slug(hanzi)}`,
      hanzi,
      pinyin,
      ru,
      emoji,
      note,
    })),
    sentences: seed.sentences.map(([tokens, ru], j) => ({
      id: `${id}-s${j + 1}`,
      tokens: tokens.split(' '),
      ru,
    })),
  }
})

export const allWords: Word[] = units.flatMap((u) => u.words)
export const wordById = new Map(allWords.map((w) => [w.id, w]))
export const wordByHanzi = new Map<string, Word>()
for (const w of allWords) if (!wordByHanzi.has(w.hanzi)) wordByHanzi.set(w.hanzi, w)

export const allSentences: Sentence[] = units.flatMap((u) => u.sentences)
export const sentenceById = new Map(allSentences.map((s) => [s.id, s]))

export const unitOfWord = new Map<string, Unit>()
for (const u of units) for (const w of u.words) unitOfWord.set(w.id, u)

const LESSON_TITLES = ['Новые слова', 'Ещё слова', 'Закрепление', 'Фразы', 'Практика']

function buildLessons(): Lesson[] {
  const lessons: Lesson[] = []
  for (const u of units) {
    const chunks: string[][] = []
    const ids = u.words.map((w) => w.id)
    const size = Math.ceil(ids.length / Math.ceil(ids.length / 4))
    for (let i = 0; i < ids.length; i += size) chunks.push(ids.slice(i, i + size))
    const assigned = new Set<string>()
    chunks.forEach((chunk, i) => {
      const known = new Set(chunks.slice(0, i + 1).flat().map((id) => wordById.get(id)!.hanzi))
      const isLast = i === chunks.length - 1
      const fits = u.sentences
        .filter((s) => !assigned.has(s.id))
        .filter((s) => s.tokens.every((t) => known.has(t) || !u.words.some((w) => w.hanzi === t)))
        .slice(0, isLast ? undefined : 2)
      fits.forEach((s) => assigned.add(s.id))
      lessons.push({
        id: `${u.id}-l${i + 1}`,
        unitId: u.id,
        index: i,
        title: LESSON_TITLES[i] ?? `Урок ${i + 1}`,
        kind: 'learn',
        newWordIds: chunk,
        sentenceIds: fits.map((s) => s.id),
      })
    })
    lessons.push({
      id: `${u.id}-review`,
      unitId: u.id,
      index: chunks.length,
      title: 'Повторение юнита',
      kind: 'review',
      newWordIds: [],
      sentenceIds: u.sentences.map((s) => s.id),
    })
    lessons.push({
      id: `${u.id}-test`,
      unitId: u.id,
      index: chunks.length + 1,
      title: 'Испытание',
      kind: 'test',
      newWordIds: [],
      sentenceIds: u.sentences.map((s) => s.id),
    })
  }
  return lessons
}

export const lessons: Lesson[] = buildLessons()
export const lessonById = new Map(lessons.map((l) => [l.id, l]))
export const lessonsOfUnit = (unitId: string) => lessons.filter((l) => l.unitId === unitId)

export function tokenWord(token: string): Word | undefined {
  return wordByHanzi.get(token)
}
